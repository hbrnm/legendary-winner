import {expect,test} from "@playwright/test";
import {signUp,syncNow} from "./helpers";

test("un membru simplu modifică bugetul și adaugă venituri vizibile proprietarului",async({browser})=>{
 const owner=await signUp(browser,"IncomeOwner");
 await owner.waitForURL(/gospodarie/);
 await owner.getByLabel("Numele gospodăriei").fill("Familia venituri");
 await owner.getByRole("button",{name:"Creează gospodăria"}).click();
 await expect(owner.getByText("Familia venituri").first()).toBeVisible();
 await owner.goto("/buget/");await syncNow(owner);
 await owner.getByRole("button",{name:"Acțiuni buget",exact:true}).click();
 await owner.getByRole("dialog",{name:"Buget",exact:true}).getByRole("button",{name:"Adaugă venit",exact:true}).click();
 const first=owner.getByRole("dialog",{name:"Venituri și alocare",exact:true});
 await first.getByLabel("Numele venitului 1",{exact:true}).fill("Salariu soț");
 await first.getByLabel("Venitul 1 (RON)",{exact:true}).fill("3000");
 await first.getByRole("button",{name:"Adaugă o sursă",exact:true}).click();
 await first.getByLabel("Numele venitului 2",{exact:true}).fill("Salariu soție");
 await first.getByLabel("Venitul 2 (RON)",{exact:true}).fill("2000");
 await first.getByLabel("Buget pentru cheltuieli (RON)",{exact:true}).fill("4000");
 await first.getByRole("button",{name:"Salvează veniturile",exact:true}).click();
 await expect(first).not.toBeVisible();await syncNow(owner);
 await owner.goto("/gospodarie/");
 await owner.getByRole("button",{name:"Invită pe cineva",exact:true}).click();
 await owner.getByRole("button",{name:"Creează linkul de invitație",exact:true}).click();
 const link=new URL((await owner.locator("p",{hasText:"/invitatie/?token="}).textContent())!.trim());
 await owner.keyboard.press("Escape");
 const member=await signUp(browser,"IncomeMember",link.pathname+link.search);
 await member.waitForURL(/invitatie/);
 await member.getByRole("button",{name:"Accept invitația",exact:true}).click();
 await member.waitForURL(u=>u.pathname==="/");
 await member.goto("/gospodarie/");
 await expect(member.getByText("Rolul tău: Membru",{exact:true})).toBeVisible();
 await member.goto("/buget/");await syncNow(member);
 await member.getByRole("button",{name:"Modifică bugetul Bugetul lunii",exact:true}).click();
 const budget=member.getByRole("dialog",{name:"Modifică bugetul",exact:true});
 const save=budget.getByRole("button",{name:"Salvează",exact:true});
 await expect(save).toBeEnabled();
 await budget.getByLabel("Suma (lei)",{exact:true}).fill("4500");
 await save.click();await expect(budget).not.toBeVisible();await syncNow(member);
 await owner.goto("/buget/");await syncNow(owner);
 const ownerPanel=owner.getByRole("region",{name:"Venituri lunare",exact:true});
 await expect(ownerPanel).toContainText(/4[.]?500,00\s+RON/);
 await member.getByRole("button",{name:"Acțiuni buget",exact:true}).click();
 await member.getByRole("dialog",{name:"Buget",exact:true}).getByRole("button",{name:"Adaugă venit",exact:true}).click();
 const sheet=member.getByRole("dialog",{name:"Venituri și alocare",exact:true});
 await sheet.getByLabel("Numele venitului 3",{exact:true}).fill("Alte venituri");
 await sheet.getByLabel("Venitul 3 (RON)",{exact:true}).fill("500");
 await sheet.getByRole("button",{name:"Salvează veniturile",exact:true}).click();
 await expect(sheet).not.toBeVisible();await syncNow(member);await syncNow(owner);
 await expect(ownerPanel).toContainText("Alte venituri");
 await expect(ownerPanel).toContainText(/5[.]?500,00\s+RON/);
 await expect(ownerPanel).toContainText(/1[.]?000,00\s+RON nealocați/);
 await member.reload();await expect(member.getByRole("region",{name:"Venituri lunare",exact:true})).toContainText("Alte venituri");
});
