import { expect, test, type Page } from "@playwright/test";
import { start } from "./helpers";

async function addExpense(page: Page, description: string, amount: string, category: string, date = "2026-03-08") {
  await page.getByRole("button", { name: "Acțiuni buget", exact: true }).click();
  await page.getByRole("dialog", { name: "Buget", exact: true }).getByRole("button", { name: "Adaugă cheltuială", exact: true }).click();
  const form = page.getByRole("dialog", { name: "Cheltuială", exact: true });
  await form.getByLabel("Notă scurtă (opțional)", { exact: true }).fill(description);
  await form.getByLabel("Sumă (RON)", { exact: true }).fill(amount);
  await form.getByLabel("Data plății", { exact: true }).fill(date);
  await expect(form.getByLabel("Data plății", { exact: true })).toHaveAttribute("max", "2026-03-08");
  await form.getByLabel("Toate categoriile", { exact: true }).selectOption(category);
  expect(await form.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(0);
  await form.getByRole("button", { name: "Salvează", exact: true }).click();
  await expect(form).not.toBeVisible();
}

test("bugetul familiei: cheltuieli, categorii, luni, persistență și export pe telefon", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 });
  await start(page, "/buget/");
  await addExpense(page, "Școală martie", "800", "educatie");
  await addExpense(page, "Autobuz", "50", "transport");
  await addExpense(page, "Pantofi copii", "120", "haine");
  const total = page.getByText("Cheltuit în lună", { exact: true }).locator("..");
  await expect(total).toContainText("970,00");
  const trip = page.getByText("Media unei ieșiri la cumpărături", { exact: true }).locator("..");
  await expect(trip).toContainText("—");
  await page.getByRole("button", { name: "Setează bugetul lunar", exact: true }).click();
  const budget = page.getByRole("dialog", { name: "Buget nou" });
  await expect(budget.getByLabel("Pentru", { exact: true })).toHaveValue("familie");
  await budget.getByLabel("Suma (lei)", { exact: true }).fill("1000");
  await budget.getByLabel("Pentru", { exact: true }).selectOption("cheltuiala");
  await budget.getByLabel("Categoria", { exact: true }).selectOption("educatie");
  await budget.getByLabel("Nume (opțional)", { exact: true }).fill("Buget școală");
  await budget.getByRole("button", { name: "Salvează", exact: true }).click();
  const schoolBudget = page.getByRole("button", { name: "Modifică bugetul Buget școală" }).locator("../..");
  await expect(schoolBudget).toContainText("800,00");
  await expect(schoolBudget).toContainText(/200,00\s+RON\s+rămași/);
  await page.getByRole("button", { name: "Adaugă un buget", exact: true }).click();
  await budget.getByLabel("Suma (lei)", { exact: true }).fill("2000");
  await budget.getByLabel("Nume (opțional)", { exact: true }).fill("Bugetul familiei");
  await budget.getByRole("button", { name: "Salvează", exact: true }).click();
  await expect(budget).not.toBeVisible();
  await expect(page.getByRole("button", {name:"Modifică bugetul Bugetul familiei",exact:true})).toBeVisible();
  await page.goto("/");
  await expect(page.getByRole("link", { name: /1[.]?030,00\s+RON\s+rămași\s+din\s+2[.]?000,00\s+RON/ })).toBeVisible();
  await expect(page.getByRole("progressbar", { name: "Bugetul lunii folosit" })).toHaveAttribute("aria-valuenow", "49");
  await page.goto("/buget/tranzactii/");
  await page.getByRole("button", { name: "Modifică cheltuiala Autobuz", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Modifică cheltuiala Autobuz", exact: true });
  await edit.getByLabel("Suma (lei)", { exact: true }).fill("60");
  await edit.getByRole("button", { name: "Salvează", exact: true }).click();
  await page.getByRole("button", { name: "Șterge cheltuiala Pantofi copii", exact: true }).click();
  const remove = page.getByRole("dialog", { name: "Ștergi această cheltuială?" });
  await remove.getByRole("button", { name: "Anulează", exact: true }).click();
  await expect(page.getByRole("button", { name: "Modifică cheltuiala Pantofi copii" })).toBeVisible();
  await page.getByRole("button", { name: "Șterge cheltuiala Pantofi copii", exact: true }).click();
  await remove.getByRole("button", { name: "Șterge", exact: true }).click();
  await page.getByRole("link", { name: "Înapoi la buget", exact: true }).click();
  await expect(total).toContainText("860,00");
  await page.getByRole("button", { name: "Luna anterioară", exact: true }).click();
  await addExpense(page, "Școală februarie", "100", "educatie", "2026-02-20");
  await expect(total).toContainText("100,00");
  await page.reload();
  await expect(total).toContainText("860,00");
  await page.getByRole("button", { name: "Luna anterioară", exact: true }).click();
  await expect(total).toContainText("100,00");
  await page.getByRole("link", { name: /^Tranzacții/ }).click();
  await page.getByRole("button", { name: "Luna anterioară", exact: true }).click();
  await expect(page.getByRole("button", { name: "Modifică cheltuiala Școală februarie" })).toBeVisible();
  await page.getByRole("button", { name: "Modifică cheltuiala Școală februarie" }).click();
  const previous = page.getByRole("dialog", { name: "Modifică cheltuiala Școală februarie", exact: true });
  await previous.getByLabel("Suma (lei)", { exact: true }).fill("110");
  await previous.getByRole("button", { name: "Salvează", exact: true }).click();
  await page.getByRole("link", { name: "Înapoi la buget", exact: true }).click();
  await page.getByRole("button", { name: "Luna anterioară", exact: true }).click();
  await expect(total).toContainText("110,00");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportă tot", exact: true }).click();
  const exported = await download;
  const stream = await exported.createReadStream();
  let csv = "";
  for await (const chunk of stream!) csv += chunk.toString();
  expect(csv).toContain("Școală martie");
  expect(csv).toContain("Școală februarie");
  expect(csv).toContain("Autobuz");
  expect(csv).not.toContain("Pantofi copii");
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0);
});
