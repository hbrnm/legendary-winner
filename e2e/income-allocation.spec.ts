import {expect,test} from "@playwright/test";
import {start} from "./helpers";
test("veniturile se cumulează, iar plafonul de cheltuieli rămâne ales separat",async({page})=>{
 await start(page,"/buget/");
 await page.getByRole("button",{name:"Acțiuni buget",exact:true}).click();
 await page.getByRole("dialog",{name:"Buget",exact:true}).getByRole("button",{name:"Adaugă venit",exact:true}).click();
 let sheet=page.getByRole("dialog",{name:"Venituri și alocare",exact:true});
 await sheet.getByLabel("Numele venitului 1",{exact:true}).fill("Salariu soț");
 await sheet.getByLabel("Venitul 1 (RON)",{exact:true}).fill("3000");
 await sheet.getByRole("button",{name:"Adaugă o sursă",exact:true}).click();
 await sheet.getByLabel("Numele venitului 2",{exact:true}).fill("Salariu soție");
 await sheet.getByLabel("Venitul 2 (RON)",{exact:true}).fill("2000");
 await sheet.getByLabel("Buget pentru cheltuieli (RON)",{exact:true}).fill("4000");
 await sheet.getByRole("button",{name:"Salvează veniturile",exact:true}).click();
 await expect(sheet).not.toBeVisible();
 const panel=page.getByRole("region",{name:"Venituri lunare",exact:true});
 await expect(panel).toContainText(/5[.]?000,00\s+RON/);
 await expect(panel).toContainText(/1[.]?000,00\s+RON nealocați/);
 await page.reload();await expect(panel).toContainText("Salariu soție");
 await page.goto("/");
 await expect(page.getByRole("link",{name:/Buget lunar\s+4[.]?000,00\s+RON.*Îți mai rămân\s+4[.]?000,00\s+RON/})).toBeVisible();
 await page.goto("/buget/");
 await page.getByRole("button",{name:"Modifică veniturile și alocarea",exact:true}).click();
 sheet=page.getByRole("dialog",{name:"Venituri și alocare",exact:true});
 await expect(sheet.getByLabel("Buget pentru cheltuieli (RON)",{exact:true})).toHaveValue("4000,00");
 await sheet.getByRole("button",{name:"Elimină venitul 2",exact:true}).click();
 await sheet.getByRole("button",{name:"Salvează veniturile",exact:true}).click();
 await expect(sheet).not.toBeVisible();
 await expect(panel).toContainText(/1[.]?000,00\s+RON peste venituri/);
 await expect(panel).not.toContainText("Salariu soție");
});
