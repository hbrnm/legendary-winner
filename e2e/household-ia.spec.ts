import { expect, test } from "@playwright/test";
import { createList, quickAdd, start } from "./helpers";

test("IA: captură universală, categorie școală, sold și disponibil zilnic", async ({ page }) => {
  await page.setViewportSize({width:393,height:852});
  await start(page,"/buget/");
  await page.getByRole("button",{name:"Setează bugetul lunar",exact:true}).click();
  const cap=page.getByRole("dialog",{name:"Buget nou"});
  await cap.getByLabel("Suma (lei)",{exact:true}).fill("1000");
  await cap.getByRole("button",{name:"Salvează",exact:true}).click();
  await page.getByRole("button",{name:"Acțiuni buget",exact:true}).click();
  await page.getByRole("dialog",{name:"Buget",exact:true}).getByRole("button",{name:"Adaugă cheltuială",exact:true}).click();
  const sheet=page.getByRole("dialog",{name:"Cheltuială",exact:true});
  await expect(sheet.getByLabel("Sumă (RON)")).toBeFocused();
  expect(await sheet.getByLabel("Sumă (RON)").evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(32);
  await sheet.getByLabel("Sumă (RON)").fill("100");
  await sheet.getByRole("button",{name:"+ Alt loc",exact:true}).click();
  await sheet.getByLabel("Numele locului").fill("Școala copiilor");
  await sheet.getByLabel("Toate categoriile").selectOption("educatie");
  await sheet.getByLabel("Notă scurtă (opțional)").fill("Caiete și rechizite");
  await sheet.getByRole("button",{name:"Salvează",exact:true}).click();
  await expect(sheet).not.toBeVisible();
  await expect(page.getByText("Cheltuit în lună",{exact:true}).locator("..")).toContainText("100,00");
  // Lista de tranzacții nu mai stă în pagina de buget; se deschide în ecranul ei.
  await expect(page.getByRole("radio",{name:"Manuale",exact:true})).toHaveCount(0);
  await page.getByRole("link",{name:/^Tranzacții/}).click();
  await page.getByRole("radio",{name:"Manuale",exact:true}).click();
  await expect(page.getByText("Caiete și rechizite",{exact:true})).toBeVisible();
  await page.getByRole("radio",{name:"Bonuri",exact:true}).click();
  await expect(page.getByText("Caiete și rechizite",{exact:true})).toHaveCount(0);
  await page.goto("/buget/");
  await expect(page.getByText(/37,50\s+RON\/zi/)).toBeVisible();
  await page.goto("/");
  await expect(page.getByText(/900,00\s+RON/).first()).toBeVisible();
  await expect(page.getByRole("heading",{name:"Azi la masă",exact:true})).toBeVisible();
  const nav=page.locator(".app-mobile-nav");
  expect(await nav.getByRole("link").allTextContents()).toEqual(["Acasă","Rețete","Cămară","Cumpărături","Buget"]);
  const bg=await page.locator("body").evaluate(el=>getComputedStyle(el).backgroundColor);
  expect(await page.locator(".app-topbar").evaluate(el=>getComputedStyle(el).backgroundColor)).toBe(bg);
  await page.screenshot({path:"test-results/ia-home.png",fullPage:true});
});

test("IA: total fără preț individual, listă parțială și cămară fără dubluri", async ({page})=>{
  await start(page);
  await createList(page,"De cumpărat azi");
  const listUrl=page.url();
  await quickAdd(page,"1 l lapte");
  await quickAdd(page,"1 kg făină");
  await page.getByRole("checkbox",{name:/Bifează Lapte/}).click();
  await page.getByRole("button",{name:"Am plătit",exact:true}).click();
  const paid=page.getByRole("dialog",{name:"Am plătit",exact:true});
  await paid.getByLabel("Total plătit (lei)").fill("14,75");
  await paid.getByLabel("Locul cumpărăturilor",{exact:true}).selectOption({label:"Auchan"});
  await paid.getByRole("button",{name:"Finalizează cumpărăturile",exact:true}).click();
  await expect(paid).not.toBeVisible();
  await expect(page.getByRole("checkbox",{name:/Bifează Făină/})).toBeVisible();
  await expect(page.getByRole("button",{name:"Am plătit",exact:true})).toBeDisabled();
  await page.goto("/buget/");
  const total=page.getByText("Cheltuit în lună",{exact:true}).locator("..");
  await expect(total).toContainText("14,75");
  await page.reload();
  await expect(total).toContainText("14,75");
  await expect(page.getByText("Nealocat",{exact:true}).first()).toBeVisible();
  await page.goto("/cumparaturi/istoric/");
  await expect(page.locator("main").getByRole("button").filter({hasText:"Auchan"}).first()).toContainText("14,75");
  await page.goto("/camara/");
  await page.getByRole("searchbox", { name: "Caută în cămară" }).fill("Lapte integral");
  await expect(page.getByText("Lapte integral",{exact:true}).first()).toBeVisible();
  await page.goto(listUrl);
  await expect(page.getByRole("button",{name:"Am plătit",exact:true})).toBeDisabled();
});

test("IA: scanarea se deschide în panoul comun și păstrează contextul listei",async({page})=>{
  await start(page);
  await createList(page,"Bonul pieței");
  await quickAdd(page,"1 kg roșii");
  await page.getByRole("checkbox",{name:/Bifează Roșii/}).click();
  await page.getByRole("button",{name:"Am plătit",exact:true}).click();
  await page.getByRole("dialog",{name:"Am plătit",exact:true}).getByRole("button",{name:"Scanează bonul",exact:true}).click();
  const capture=page.getByRole("dialog",{name:"Cheltuială",exact:true});
  await expect(capture.getByRole("button",{name:"Fotografiază bonul",exact:true})).toBeVisible();
  await capture.getByRole("button",{name:"Introducere manuală",exact:true}).click();
  await expect(capture).not.toBeVisible();
  const checkout=page.getByRole("dialog",{name:"Am plătit",exact:true});
  await expect(checkout.getByLabel("Total plătit (lei)")).toBeVisible();
  await checkout.getByRole("button",{name:"Scanează bonul",exact:true}).click();
  await expect(capture.getByTestId("bon-camera")).toHaveAttribute("capture","environment");
  await page.screenshot({path:"test-results/ia-capture.png",fullPage:true});
});
